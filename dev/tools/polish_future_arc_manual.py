def lua_encode(value: str, quote: str) -> str:
    value = value.replace("\\", "\\\\").replace("\n", "\\n")
    return value.replace(quote, "\\" + quote)


def apply() -> int:
    """Valide la configuration entière, puis applique les écritures en bloc."""
    changed = 0
    seen: set[tuple[str, str]] = set()
    pending: dict[Path, str] = {}

    # Première phase sans effet de bord : toute clé mal configurée ou réplique
    # illisible fait échouer l'outil avant la moindre écriture.
    for path in sorted(SCENES.glob("*.lua")):
        lines = path.read_text(encoding="utf-8").splitlines(keepends=True)
        output: list[str] = []
        for line in lines:
            tag_match = TAG.search(line)
            key = (path.name, tag_match.group(1)) if tag_match else None
            if key not in CORRECTIONS:
                output.append(line)
                continue
            pattern = SINGLE if SINGLE.search(line) else DOUBLE
            match = pattern.search(line)
            if match is None:
                raise ValueError(f"réplique illisible : {path}:{tag_match.group(1)}")
            quote = "'" if pattern is SINGLE else '"'
            encoded = lua_encode(CORRECTIONS[key], quote)
            updated = line[:match.start("body")] + encoded + line[match.end("body"):]
            output.append(updated)
            changed += int(updated != line)
            seen.add(key)
        pending[path] = "".join(output)

    missing = set(CORRECTIONS) - seen
    if missing:
        raise RuntimeError("corrections sans réplique correspondante : " + ", ".join(map(str, sorted(missing))))

    # Seconde phase : elle n'est atteinte qu'après validation de toutes les clés.
    for path, text in pending.items():
        if text != path.read_text(encoding="utf-8"):
            path.write_text(text, encoding="utf-8")
